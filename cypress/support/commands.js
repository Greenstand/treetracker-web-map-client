// Take a screenshot of the page when its web fonts are loaded. Without this
// wait, a screenshot can show the fallback font of the browser.
Cypress.Commands.add('screenshotPage', () => {
  cy.document().its('fonts.status').should('equal', 'loaded');
  cy.screenshot();
});
